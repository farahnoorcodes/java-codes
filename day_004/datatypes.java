package day_004;

public class datatypes {
 

    public static void main(String[] args) {
           // Java has two main categories of data types:

// 1. Primitive Data Types (8 total)

// These store simple values directly in memory.

// Numbers (integer):

// byte – 1 byte, range -128 to 127
// short – 2 bytes, range -32,768 to 32,767
// int – 4 bytes, range ~-2.1 billion to 2.1 billion (most commonly used)
// long – 8 bytes, for very large numbers (needs L suffix, e.g. long x = 100000L;)

// Numbers (decimal):

// float – 4 bytes, decimal numbers (needs f suffix, e.g. float y = 3.14f;)
// double – 8 bytes, decimal numbers (default for decimals, more precise)

// Others:

// char – single character, written in single quotes, e.g. char grade = 'A';
// boolean – only true or false


// 2. Non-Primitive (Reference) Data Types

// These store references to objects, not the value itself.

// String – text, e.g. String name = "Farah";
// Arrays
// Classes
// Interfaces


// Quick example

int age = 21;
double price = 99.99;
char letter = 'F';
boolean isStudent = true;
String city = "Multan";
    }

}
